// Bundles the worker into dist/, the manifest's `main`. Installed plugins don't run `npm install`,
// so the driver, ssh2 and the AWS SDK go into the bundle. Run after changing anything under
// src/worker, src/shared or src/protocol.ts (or keep `npm run build:watch` running):
//   npm run build
// Writes dist/worker.mjs and dist/shell-thread.mjs, the shell's script thread with its own `bson`.
// Not bundled: native modules (`kerberos`, ssh2's optional `cpu-features` and `sshcrypto.node`)
// and the driver's optional peers it loads only when a connection asks for them. The driver
// reports each one as missing; Kerberos gets its own message (src/worker/client.ts).
import { build, context } from 'esbuild'
import { rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outdir = join(root, 'dist')
const watch = process.argv.includes('--watch')

const options = {
  absWorkingDir: root,
  entryPoints: {
    worker: 'src/worker.ts',
    'shell-thread': 'dev/shell-thread-entry.mjs'
  },
  outdir,
  outExtension: { '.js': '.mjs' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  minify: false,
  legalComments: 'inline',
  charset: 'utf8',
  logLevel: 'info',
  external: [
    'kerberos',
    'cpu-features',
    '*.node',
    '@mongodb-js/zstd',
    'snappy',
    'mongodb-client-encryption',
    'gcp-metadata',
    'socks'
  ],
  banner: {
    js:
      '// Generated by dev/build-worker.mjs from src/ and the npm packages in package.json. Do not edit.\n' +
      "import { createRequire as __mongoStudioCreateRequire } from 'node:module';\n" +
      "import { fileURLToPath as __mongoStudioFileURLToPath } from 'node:url';\n" +
      "import { dirname as __mongoStudioDirname } from 'node:path';\n" +
      'const require = __mongoStudioCreateRequire(import.meta.url);\n' +
      'const __filename = __mongoStudioFileURLToPath(import.meta.url);\n' +
      'const __dirname = __mongoStudioDirname(__filename);'
  }
}

rmSync(outdir, { recursive: true, force: true })
if (watch) {
  const ctx = await context(options)
  await ctx.watch()
} else {
  await build(options)
}
