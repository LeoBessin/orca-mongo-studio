// Bundles the CodeMirror pieces the shell editor uses into one ESM file, since Orca frames import
// only relative files. Run after changing the list or upgrading CodeMirror:
//   node dev/build-codemirror.mjs
// It writes src/editor/vendor/codemirror.js and the matching codemirror.d.ts, which re-exports the
// same names from the npm packages, so the editor is type-checked against the real typings.
import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src/editor/vendor')

const EXPORTS = {
  '@codemirror/state': ['EditorState', 'EditorSelection', 'Compartment', 'StateEffect', 'StateField', 'Prec', 'Transaction'],
  '@codemirror/view': ['EditorView', 'keymap', 'lineNumbers', 'highlightActiveLine', 'highlightActiveLineGutter', 'drawSelection', 'dropCursor', 'rectangularSelection', 'crosshairCursor', 'highlightSpecialChars', 'placeholder', 'Decoration', 'ViewPlugin'],
  '@codemirror/commands': ['defaultKeymap', 'history', 'historyKeymap', 'indentWithTab'],
  '@codemirror/language': ['syntaxHighlighting', 'HighlightStyle', 'bracketMatching', 'indentOnInput', 'foldGutter', 'foldKeymap'],
  '@codemirror/autocomplete': ['autocompletion', 'completionKeymap', 'closeBrackets', 'closeBracketsKeymap', 'startCompletion'],
  '@codemirror/search': ['search', 'searchKeymap', 'highlightSelectionMatches'],
  '@codemirror/lint': ['setDiagnostics', 'lintGutter'],
  '@codemirror/lang-javascript': ['javascript'],
  '@lezer/highlight': ['tags']
}
const TYPES = {
  '@codemirror/state': ['Extension', 'Text'],
  '@codemirror/view': ['ViewUpdate', 'KeyBinding'],
  '@codemirror/autocomplete': ['Completion', 'CompletionContext', 'CompletionResult', 'CompletionSource'],
  '@codemirror/lint': ['Diagnostic']
}

const lines = (kind) =>
  Object.entries(kind === 'type' ? TYPES : EXPORTS)
    .map(([pkg, names]) => `export ${kind === 'type' ? 'type ' : ''}{ ${names.join(', ')} } from '${pkg}'`)
    .join('\n')

const entry = lines('value')
const result = await build({
  stdin: { contents: entry, resolveDir: root, loader: 'js' },
  bundle: true,
  format: 'esm',
  minify: true,
  legalComments: 'eof',
  target: 'es2022',
  write: false
})
mkdirSync(out, { recursive: true })
const banner = '// Generated by dev/build-codemirror.mjs from the CodeMirror packages (MIT). Do not edit.\n'
writeFileSync(join(out, 'codemirror.js'), banner + result.outputFiles[0].text)
writeFileSync(join(out, 'codemirror.d.ts'), `${banner}${entry}\n${lines('type')}\n`)
console.log(`codemirror.js: ${(result.outputFiles[0].contents.length / 1024).toFixed(0)} KiB`)
