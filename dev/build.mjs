// Bundles what the manifest runs into dist/, readable: not minified, so what ships can be read
// against the source. Orca's plugin directory holds minified code for review. Run after changing anything under src/ other than the
// shell editor (or keep `npm run build:watch` running):
//   npm run build
//
// - dist/worker.mjs, the manifest's `main`, and dist/shell-thread.mjs, the shell's script thread
//   with its own `bson`. Installed plugins don't run `npm install`, so the driver, ssh2 and the
//   AWS SDK go into the bundle. Not bundled: native modules (`kerberos`, ssh2's optional
//   `cpu-features` and `sshcrypto.node`) and the driver's optional peers it loads only when a
//   connection asks for them. The driver reports each one as missing; Kerberos gets its own
//   message (src/worker/client.ts).
// - dist/panel.js, the panel's entry. Orca serves an installed plugin's frame at most 32 requests
//   at a time and answers 503 past that, which fails a module graph as wide as the panel's (about
//   60 files loaded at once), so the panel ships as one module. `orca` stays external.
//   dist/panel.check.ts hands the panel's check scenarios (src/panel.check.ts) to the bundle.
import { build, context } from 'esbuild'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outdir = join(root, 'dist')
const watch = process.argv.includes('--watch')
const generated = (from) => `// Generated by dev/build.mjs from ${from}. Do not edit.\n`

const common = {
  absWorkingDir: root,
  outdir,
  bundle: true,
  format: 'esm',
  minify: false,
  legalComments: 'inline',
  charset: 'utf8',
  logLevel: 'info'
}

// The driver's connection-string parser (mongodb-connection-string-url) takes `URL` from the
// `whatwg-url` package, which brings its own Unicode tables (tr46): about 340 KB of the worker.
// Node's own `URL` is the same WHATWG URL, so the bundle uses that instead.
const nodeUrl = {
  name: 'node-url',
  setup(b) {
    b.onResolve({ filter: /^whatwg-url$/ }, () => ({ path: 'whatwg-url', namespace: 'node-url' }))
    b.onLoad({ filter: /.*/, namespace: 'node-url' }, () => ({
      contents: 'module.exports = { URL: globalThis.URL, URLSearchParams: globalThis.URLSearchParams }',
      loader: 'js'
    }))
  }
}

const worker = {
  ...common,
  entryPoints: {
    worker: 'src/worker.ts',
    'shell-thread': 'dev/shell-thread-entry.mjs'
  },
  outExtension: { '.js': '.mjs' },
  plugins: [nodeUrl],
  platform: 'node',
  target: 'node22',
  external: [
    'kerberos',
    'cpu-features',
    '*.node',
    '@mongodb-js/zstd',
    'snappy',
    'mongodb-client-encryption',
    'gcp-metadata',
    'socks'
  ],
  banner: {
    js:
      generated('src/ and the npm packages in package.json') +
      "import { createRequire as __mongoStudioCreateRequire } from 'node:module';\n" +
      "import { fileURLToPath as __mongoStudioFileURLToPath } from 'node:url';\n" +
      "import { dirname as __mongoStudioDirname } from 'node:path';\n" +
      'const require = __mongoStudioCreateRequire(import.meta.url);\n' +
      'const __filename = __mongoStudioFileURLToPath(import.meta.url);\n' +
      'const __dirname = __mongoStudioDirname(__filename);'
  }
}

const panel = {
  ...common,
  entryPoints: { panel: 'src/panel.tsx' },
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  jsxImportSource: 'orca',
  external: ['orca', 'orca/*'],
  banner: { js: generated('src/panel.tsx') }
}

rmSync(outdir, { recursive: true, force: true })
mkdirSync(outdir, { recursive: true })
// `orca plugin check` and `shot --scenario` read `<entry>.check.ts`: point it at the source's.
writeFileSync(join(outdir, 'panel.check.ts'), generated('src/panel.check.ts') + "export { default } from '../src/panel.check.ts'\n")
if (watch) {
  for (const options of [worker, panel]) await (await context(options)).watch()
} else {
  await Promise.all([build(worker), build(panel)])
}
