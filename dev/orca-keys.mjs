// Snapshots Orca's default shortcuts that can fire while Mongo Studio has focus (the global and
// tab scopes), so the plugin's own keybindings and the shell editor's keys can avoid them. Run
// after upgrading Orca:
//   ELECTRON_RUN_AS_NODE=1 node dev/orca-keys.mjs
// It writes src/shared/orca-keys.ts. Shortcuts Orca leaves to text fields (allowInTextField) are
// left out: in the shell editor those keys belong to the editor.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const orca = process.env.ORCA_APP ?? '/usr/lib/orca-ide/app.asar.unpacked/out'
const require = createRequire(import.meta.url)
const defs = require(join(orca, 'shared/keybindings/definitions.js'))
const version = JSON.parse(readFileSync(join(orca, 'package.json'), 'utf8')).version

const SCOPES = new Set(['global', 'tabs'])
const PLATFORMS = ['darwin', 'linux', 'win32']
const out = Object.fromEntries(PLATFORMS.map((p) => [p, new Set()]))
for (const def of defs.KEYBINDING_DEFINITIONS) {
  if (!SCOPES.has(def.scope) || def.allowInTextField) continue
  const digits = defs.isDigitIndexActionId?.(def.id) ?? false
  for (const p of PLATFORMS) {
    for (const chord of def.defaultBindings?.[p] ?? []) {
      // A digit-index row stands for 1 to 9.
      if (digits && /\+1$/.test(chord)) for (let d = 1; d <= 9; d++) out[p].add(chord.replace(/1$/, String(d)))
      else out[p].add(chord)
    }
  }
}

const body = PLATFORMS.map((p) => `  ${p}: [\n${[...out[p]].sort().map((k) => `    '${k}'`).join(',\n')}\n  ]`).join(',\n')
const file = `// Generated by dev/orca-keys.mjs from Orca ${version}: the default shortcuts of Orca's global and
// tab scopes, which can fire while Mongo Studio has focus. Do not edit; run the script again after
// upgrading Orca.
export const ORCA_KEYS_VERSION = '${version}'

export const ORCA_RESERVED_KEYS: Record<'darwin' | 'linux' | 'win32', readonly string[]> = {
${body}
}
`
writeFileSync(join(root, 'src/shared/orca-keys.ts'), file)
console.log(`Wrote src/shared/orca-keys.ts (Orca ${version}): ${PLATFORMS.map((p) => `${p} ${out[p].size}`).join(', ')}`)
